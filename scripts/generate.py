#!/usr/bin/env python3
"""Generate the Java SDK from its pinned public OpenAPI contract, offline."""
import argparse
import hashlib
import html
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVA = 'src/main/java/com/raims/'
MARKER = '// Generated by scripts/generate.py. Do not edit.\n'
VERBS = {'get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace'}
RESERVED = {'class', 'default', 'new', 'return', 'switch', 'case', 'enum', 'public', 'private', 'protected', 'static', 'final', 'this', 'super', 'throw', 'throws', 'void', 'null', 'true', 'false', 'instanceof', 'interface', 'package', 'import', 'while', 'for', 'if', 'else', 'try', 'catch', 'finally', 'assert', 'extends', 'implements', 'native', 'volatile', 'transient', 'synchronized', 'abstract', 'boolean', 'byte', 'short', 'int', 'long', 'float', 'double', 'char', 'const', 'goto', 'break', 'continue', 'do', 'strictfp'}


def name(value):
    value = unicodedata.normalize('NFKD', value).encode('ascii', 'ignore').decode()
    result = ''.join(p[:1].upper() + p[1:] for p in re.findall('[A-Za-z0-9]+', value))
    return 'Value' + result if not result or result[0].isdigit() else result


def variable(value):
    value = name(value)
    result = value[0].lower() + value[1:]
    return result + 'Value' if result in RESERVED else result


def literal(value):
    return json.dumps(value, ensure_ascii=True)


def constant_name(value):
    value = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', value)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', value).upper()


def javadoc(value, indent=''):
    text = html.escape(' '.join(str(value).split()), quote=False).replace('*/', '* /')
    return indent + '/** ' + text + ' */\n' if text else ''


class Generator:
    def __init__(self):
        self.outputs = {}
        self.source = json.loads((ROOT / 'contracts/source.json').read_text(encoding='utf-8-sig'))
        raw = (ROOT / 'contracts/openapi.json').read_bytes()
        if hashlib.sha256(raw).hexdigest() != self.source['sha256']:
            raise ValueError('Pinned contract SHA-256 mismatch')
        self.spec = json.loads(raw)
        self.schemas = dict(self.spec['components']['schemas'])
        self.inputs = set()
        self.models = set()
        self.services = json.loads((ROOT / 'contracts/service-map.json').read_text(encoding='utf-8-sig'))
        self.operations = {}
        for path, item in self.spec['paths'].items():
            for method, op in item.items():
                if method not in VERBS:
                    continue
                key = op['operationId']
                if key in self.operations or op.get('x-raims-availability', 'production') != 'production':
                    raise ValueError('Duplicate or unpublished operation: ' + key)
                self.operations[key] = dict(op, method=method.upper(), path=path, parameters=item.get('parameters', []) + op.get('parameters', []))
        mapped = [key for methods in self.services.values() for key in methods.values()]
        if len(set(mapped)) != len(mapped) or set(mapped) != set(self.operations) or len(mapped) != self.source['operations']:
            raise ValueError('Service map must cover every operation exactly once')
        self.validate(self.spec)
        for op in self.operations.values():
            schema = op.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema')
            if schema:
                self.mark_context(schema, self.inputs)
            for status, response in op['responses'].items():
                if status.isdigit() and 200 <= int(status) < 300:
                    schema = self.resolve(response).get('content', {}).get('application/json', {}).get('schema')
                    if schema:
                        self.mark_context(schema, self.models)
        self.models.update(set(self.schemas) - self.inputs)

    def resolve(self, schema):
        if '$ref' not in schema:
            return schema
        ref = schema['$ref']
        if not ref.startswith('#/components/'):
            raise ValueError('External reference is unsupported: ' + ref)
        value = self.spec
        for part in ref[2:].split('/'):
            value = value[part.replace('~1', '/').replace('~0', '~')]
        return dict(value, **{k: v for k, v in schema.items() if k != '$ref'})

    def validate(self, value):
        if isinstance(value, list):
            for v in value:
                self.validate(v)
        elif isinstance(value, dict):
            if '$ref' in value:
                self.resolve(value)
            if 'oneOf' in value or 'allOf' in value:
                raise ValueError('Unsupported schema composition')
            if 'anyOf' in value and (len(value['anyOf']) != 2 or sum(v.get('type') == 'null' for v in value['anyOf']) != 1):
                raise ValueError('Only nullable anyOf is supported')
            for v in value.values():
                self.validate(v)

    def normalize(self, schema):
        schema = dict(schema)
        if 'anyOf' in schema:
            child = next(v for v in schema.pop('anyOf') if v.get('type') != 'null')
            schema = dict(child, **schema)
            schema['nullable'] = True
        return schema

    def nullable(self, schema):
        schema = self.type_schema(schema)
        return schema.get('nullable', False) or schema.get('type') == 'null' or isinstance(schema.get('type'), list) and 'null' in schema['type']

    def schema_key(self, reference):
        prefix = '#/components/schemas/'
        if not reference.startswith(prefix):
            raise ValueError('A Java type requires a local schema reference: ' + reference)
        return reference[len(prefix):].replace('~1', '/').replace('~0', '~')

    def type_schema(self, schema):
        schema = self.normalize(schema)
        seen = set()
        while '$ref' in schema:
            key = self.schema_key(schema['$ref'])
            if key in seen:
                raise ValueError('Cyclic schema alias: ' + key)
            seen.add(key)
            schema = self.normalize(dict(self.schemas[key], **{k: v for k, v in schema.items() if k != '$ref'}))
        return schema

    def kind(self, schema):
        kind = schema.get('type')
        return next((value for value in kind if value != 'null'), 'null') if isinstance(kind, list) else kind

    def mark_context(self, schema, target):
        schema = self.normalize(schema)
        if '$ref' in schema:
            key = self.schema_key(schema['$ref'])
            if key in target:
                return
            target.add(key)
            schema = self.type_schema(schema)
        for v in schema.get('properties', {}).values():
            self.mark_context(v, target)
        if 'items' in schema:
            self.mark_context(schema['items'], target)
        if isinstance(schema.get('additionalProperties'), dict):
            self.mark_context(schema['additionalProperties'], target)

    def typename(self, key, is_input=None):
        is_input = key in self.inputs if is_input is None else is_input
        return key[:-7] + 'Params' if is_input and key.endswith('Request') else key

    def package(self, is_input):
        return 'com.raims.param.' if is_input else 'com.raims.model.'

    def jtype(self, schema, owner, field, is_input, references=()):
        schema = self.normalize(schema)
        if '$ref' in schema:
            key = self.schema_key(schema['$ref'])
            self.mark_context(schema, self.inputs if is_input else self.models)
            resolved = self.type_schema(schema)
            if self.kind(resolved) == 'object' and resolved.get('properties'):
                return self.package(is_input) + self.typename(key, is_input)
            if key in references:
                raise ValueError('Recursive non-object schema reference: ' + key)
            return self.jtype(resolved, owner, field, is_input, references + (key,))
        kind = self.kind(schema)
        if kind in {'string', 'integer', 'number', 'boolean'}:
            return {'string': 'String', 'integer': 'Long', 'number': 'java.math.BigDecimal', 'boolean': 'Boolean'}[kind]
        if kind == 'array':
            return 'java.util.List<' + self.jtype(schema['items'], owner, field + 'Item', is_input, references) + '>'
        if kind == 'object':
            if schema.get('properties'):
                nested = owner + name(field)
                if nested in self.schemas and self.schemas[nested] != schema:
                    raise ValueError('Nested schema collision: ' + nested)
                self.schemas[nested] = schema
                self.mark_context({'$ref': '#/components/schemas/' + nested}, self.inputs if is_input else self.models)
                return self.package(is_input) + self.typename(nested, is_input)
            extra = schema.get('additionalProperties', True)
            item = self.jtype(extra, owner, field + 'Value', is_input, references) if isinstance(extra, dict) else 'com.google.gson.JsonElement'
            return 'java.util.Map<String, ' + item + '>'
        if kind == 'null':
            return 'com.google.gson.JsonElement'
        raise ValueError('Unsupported schema type: ' + str(schema))

    def decode(self, schema, expr, owner, field, depth=0):
        typ = self.jtype(schema, owner, field, False)
        schema = self.type_schema(schema)
        if typ.startswith('com.raims.model.'):
            value = 'new ' + typ + '(' + expr + '.getAsJsonObject(), getLastResponse())'
        elif typ == 'String':
            value = expr + '.getAsString()'
        elif typ == 'Long':
            value = expr + '.getAsBigDecimal().longValueExact()'
        elif typ == 'java.math.BigDecimal':
            value = expr + '.getAsBigDecimal()'
        elif typ == 'Boolean':
            value = expr + '.getAsBoolean()'
        elif typ == 'com.google.gson.JsonElement':
            value = expr + '.deepCopy()'
        elif typ.startswith('java.util.List<'):
            symbol = 'item' if depth == 0 else 'item' + str(depth)
            item = self.decode(schema['items'], symbol, owner, field + 'Item', depth + 1)
            value = 'readList(' + expr + ', ' + symbol + ' -> ' + item + ')'
        elif typ.startswith('java.util.Map<'):
            extra = schema.get('additionalProperties', True)
            symbol = 'item' if depth == 0 else 'item' + str(depth)
            item = self.decode(extra, symbol, owner, field + 'Value', depth + 1) if isinstance(extra, dict) else symbol + '.deepCopy()'
            value = 'readMap(' + expr + ', ' + symbol + ' -> ' + item + ')'
        else:
            raise ValueError('Unsupported model field ' + typ)
        return '(' + expr + ' == null || ' + expr + '.isJsonNull() ? null : ' + value + ')'

    def render_type(self, key, schema, inp):
        schema = self.type_schema(schema)
        if self.kind(schema) != 'object':
            return
        typ = self.typename(key, inp)
        package = 'param' if inp else 'model'
        base = 'com.raims.ApiParams' if inp else 'com.raims.ApiResource'
        props = schema.get('properties', {})
        page_item = None
        if not inp and 'page' in props and 'list' in props:
            page_item = self.jtype(self.type_schema(props['list'])['items'], key, 'listItem', False)
            base = 'com.raims.RaimsCollection<' + page_item + '>'
        result = MARKER + 'package com.raims.' + package + ';\n\n'
        result += javadoc(schema.get('description', typ))
        result += 'public final class ' + typ + ' extends ' + base + ' {\n'
        if inp:
            result += '    public ' + typ + '(com.google.gson.JsonObject values) { super(values); }\n'
            result += '    public static Builder builder() { return new Builder(); }\n\n'
            result += '    public static final class Builder {\n        private final com.google.gson.JsonObject values = new com.google.gson.JsonObject();\n'
            for field, value in props.items():
                jt = self.jtype(value, key, field, True)
                settertype = {'Long': 'long', 'Boolean': 'boolean'}.get(jt, jt)
                result += javadoc(value.get('description', field), '        ')
                result += '        public Builder set' + name(field) + '(' + settertype + ' value) { values.add(' + literal(field) + ', com.raims.ApiParams.value(value)); return this; }\n'
                if self.nullable(value):
                    result += '        public Builder set' + name(field) + 'Null() { values.add(' + literal(field) + ', com.google.gson.JsonNull.INSTANCE); return this; }\n'
            result += '        public ' + typ + ' build() { return new ' + typ + '(values); }\n    }\n'
        else:
            suffix = ', ' + page_item + '::new' if page_item else ''
            result += '    public ' + typ + '(com.google.gson.JsonObject data, com.raims.ApiResponse response) { super(data, response' + suffix + '); }\n'
            seen = set()
            for field, value in props.items():
                if page_item and field in {'list', 'page'}:
                    continue
                symbol = 'get' + name(field)
                if symbol in seen or symbol in {'getClass', 'getLastResponse', 'getRawJson'}:
                    raise ValueError('Model getter collision: ' + key + '.' + field)
                seen.add(symbol)
                jt = self.jtype(value, key, field, False)
                expression = self.decode(value, 'data.get(' + literal(field) + ')', key, field)
                result += javadoc(value.get('description', field), '    ')
                result += '    public ' + jt + ' ' + symbol + '() { return ' + expression + '; }\n'
        result += '}\n'
        self.outputs[JAVA + package + '/' + typ + '.java'] = result

    def generate(self):
        operations = {}
        reference = ['# Java SDK reference\n\n', 'Generated from the pinned public contract. Parameters use `builder()`; omitted fields remain absent. The `set<Field>Null()` pattern sends explicit null. All methods accept `RequestOptions` as the last argument.\n\n', '| Method | Endpoint | Parameters | Return type | Idempotency |\n| --- | --- | --- | --- | --- |\n']
        clients = MARKER + 'package com.raims;\n\npublic class RaimsServices {\n'
        init = '    protected RaimsServices(com.raims.internal.ApiRequestor requestor) {\n'
        for service, methods in self.services.items():
            stype = name(service) + 'Service'
            if not service.startswith('simulation'):
                clients += '    private final com.raims.service.' + stype + ' ' + service + ';\n'
                clients += '    public com.raims.service.' + stype + ' ' + service + '() { return ' + service + '; }\n'
                init += '        this.' + service + ' = new com.raims.service.' + stype + '(requestor);\n'
            code = MARKER + 'package com.raims.service;\n\npublic final class ' + stype + ' {\n'
            code += '    private final com.raims.internal.ApiRequestor requestor;\n'
            code += '    public ' + stype + '(com.raims.internal.ApiRequestor requestor) { this.requestor = java.util.Objects.requireNonNull(requestor); }\n'
            for method, key in methods.items():
                op = self.operations[key]
                parameters = [self.resolve(p) for p in op['parameters']]
                paths = [p for p in parameters if p['in'] == 'path']
                queries = [p for p in parameters if p['in'] == 'query']
                body = op.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema')
                if body and queries:
                    raise ValueError('Combined query/body requires explicit support')
                if body and self.kind(self.type_schema(body)) != 'object':
                    raise ValueError('Root request bodies must be object schemas: ' + key)
                params_key = body['$ref'].split('/')[-1] if body else None
                if queries:
                    params_key = key + 'Params'
                    self.inputs.add(params_key)
                    query_schemas = {p['name']: dict(p['schema'], **{k: p[k] for k in ('description', 'deprecated', 'example') if k in p}) for p in queries}
                    self.schemas[params_key] = {'type': 'object', 'additionalProperties': False, 'properties': query_schemas, 'required': [p['name'] for p in queries if p.get('required')]}
                successes = {}
                for status, response in op['responses'].items():
                    if status.isdigit() and 200 <= int(status) < 300:
                        successes[status] = self.resolve(response).get('content', {}).get('application/json', {}).get('schema', {})
                        if successes[status] and self.kind(self.type_schema(successes[status])) != 'object':
                            raise ValueError('Root success responses must be object schemas: ' + key + ' HTTP ' + status)
                types = sorted(set(v['$ref'].split('/')[-1] for v in successes.values() if '$ref' in v))
                output = types[0] if types else None
                if len(types) > 1:
                    output = key + 'Result'
                    merged, required = {}, None
                    for typ in types:
                        child = self.type_schema(self.schemas[typ])
                        for field, val in child['properties'].items():
                            if field in merged and self.normalize(merged[field]) != self.normalize(val):
                                # Different constraints/enum values do not alter Java field types.
                                if self.jtype(merged[field], output, field, False) != self.jtype(val, output, field, False):
                                    raise ValueError('Conflicting result field types: ' + output + '.' + field)
                            merged[field] = val
                        keys = set(child.get('required', []))
                        required = keys if required is None else required.intersection(keys)
                    self.schemas[output] = {'type': 'object', 'properties': merged, 'required': sorted(required or [])}
                    self.models.add(output)
                if not output:
                    output = key + 'Result'
                    self.schemas[output] = {'type': 'object', 'properties': {}}
                    self.models.add(output)
                output_schema = self.type_schema(self.schemas[output])
                pagination = 'page' in output_schema.get('properties', {}) and 'list' in output_schema.get('properties', {})
                idem = any(p.get('name') == 'Idempotency-Key' for p in parameters)
                operations[key] = {'id': key, 'method': op['method'], 'path': op['path'], 'pathParams': [p['name'] for p in paths], 'pathSchemas': {p['name']: p['schema'] for p in paths}, 'query': {p['name']: p['schema'] for p in queries}, 'body': bool(body), 'bodyRequired': op.get('requestBody', {}).get('required', False), 'requestSchema': body, 'idempotency': idem, 'maxBodyBytes': op.get('x-raims-max-body-bytes'), 'responses': successes, 'paginated': pagination}
                signatures = ['String ' + variable(p['name']) for p in paths]
                args = [variable(p['name']) for p in paths]
                pt = 'com.raims.param.' + self.typename(params_key) if params_key else None
                rt = 'com.raims.model.' + output
                if pt:
                    signatures.append(pt + ' params')
                    args.append('params')
                description = op.get('summary', key) + '. ' + op.get('description', '')
                code += javadoc(description, '    ')
                code += '    public ' + rt + ' ' + method + '(' + ', '.join(signatures) + ') { return ' + method + '(' + ', '.join(args + ['null']) + '); }\n'
                if pt and not op.get('requestBody', {}).get('required', False):
                    pathsign = ['String ' + variable(p['name']) for p in paths]
                    pathargs = [variable(p['name']) for p in paths]
                    code += javadoc(description, '    ')
                    code += '    public ' + rt + ' ' + method + '(' + ', '.join(pathsign) + ') { return ' + method + '(' + ', '.join(pathargs + ['null', 'null']) + '); }\n'
                pathmap = 'java.util.Map.of(' + ', '.join(literal(p['name']) + ', ' + variable(p['name']) for p in paths) + ')'
                code += javadoc(description, '    ')
                code += '    public ' + rt + ' ' + method + '(' + ', '.join(signatures + ['com.raims.RequestOptions options']) + ') {\n'
                code += '        return requestor.request(' + literal(key) + ', ' + pathmap + ', ' + ('params' if pt else 'null') + ', options, ' + rt + '::new);\n    }\n'
                display = 'simulations().' + ('charges' if service == 'simulationCharges' else 'refunds') if service.startswith('simulation') else service
                reference.append('| `' + display + '().' + method + '` | `' + op['method'] + ' ' + op['path'] + '` | `' + (self.typename(params_key) if params_key else 'none') + '` | `' + output + '` | ' + ('Yes' if idem else 'No') + ' |\n')
            self.outputs[JAVA + 'service/' + stype + '.java'] = code + '}\n'
        clients += '    private final Simulations simulations;\n    public Simulations simulations() { return simulations; }\n'
        init += '        this.simulations = new Simulations(requestor);\n    }\n'
        clients += init + '    public static final class Simulations {\n'
        for child in ['Charges', 'Refunds']:
            clients += '        private final com.raims.service.Simulation' + child + 'Service ' + child.lower() + ';\n'
            clients += '        public com.raims.service.Simulation' + child + 'Service ' + child.lower() + '() { return ' + child.lower() + '; }\n'
        clients += '        private Simulations(com.raims.internal.ApiRequestor requestor) {\n'
        for child in ['Charges', 'Refunds']:
            clients += '            this.' + child.lower() + ' = new com.raims.service.Simulation' + child + 'Service(requestor);\n'
        self.outputs[JAVA + 'RaimsServices.java'] = clients + '        }\n    }\n}\n'
        done = set()
        while True:
            pending = {(key, True) for key in self.inputs} | {(key, False) for key in self.models}
            pending -= done
            if not pending:
                break
            for key, inp in sorted(pending):
                self.render_type(key, self.schemas[key], inp)
                done.add((key, inp))
        constants = {}
        def collect(value, prefix, references=()):
            value = self.normalize(value)
            if '$ref' in value:
                key = self.schema_key(value['$ref'])
                if key in references:
                    return
                resolved = self.type_schema(value)
                # Named objects own their constants; scalar and collection aliases retain the use-site names.
                if self.kind(resolved) == 'object' and resolved.get('properties'):
                    return
                value = resolved
                references += (key,)
            values = value.get('enum', [])
            labels = value.get('x-raims-enum-labels', values)
            for val, label in zip(values, labels):
                if val is None or not isinstance(label, str):
                    continue
                suffix = label if re.fullmatch('[A-Z0-9_]+', label) else name(label)
                symbol = constant_name(prefix) + '_' + constant_name(suffix)
                if symbol in constants and constants[symbol] != val:
                    raise ValueError('Enum collision: ' + symbol)
                constants[symbol] = val
            for field, child in value.get('properties', {}).items():
                collect(child, prefix + name(field), references)
            if 'items' in value:
                collect(value['items'], prefix, references)
            if isinstance(value.get('additionalProperties'), dict):
                collect(value['additionalProperties'], prefix, references)
        for key, schema in self.schemas.items():
            collect(schema, self.typename(key))
        code = MARKER + 'package com.raims;\n\npublic final class EnumValues {\n    private EnumValues() {}\n'
        for symbol, value in sorted(constants.items()):
            if isinstance(value, bool):
                kind, val = 'boolean', str(value).lower()
            elif isinstance(value, int):
                kind, val = 'long', str(value) + 'L'
            elif isinstance(value, float):
                kind, val = 'java.math.BigDecimal', 'new java.math.BigDecimal(' + literal(str(value)) + ')'
            else:
                kind, val = 'String', literal(value)
            code += '    public static final ' + kind + ' ' + symbol + ' = ' + val + ';\n'
        self.outputs[JAVA + 'EnumValues.java'] = code + '}\n'
        self.outputs['src/main/resources/com/raims/contract.json'] = json.dumps({'source': {k: self.source[k] for k in ('revision', 'sha256')}, 'services': self.services, 'operations': operations, 'schemas': self.schemas}, ensure_ascii=False, indent=2) + '\n'
        self.outputs['docs/reference.md'] = ''.join(reference)

    def write(self, check):
        bad = []
        expected = set(self.outputs)
        generated_paths = list((ROOT / 'src/main/java/com/raims').rglob('*.java')) + list((ROOT / 'src/main/resources/com/raims').glob('contract.json'))
        stale = [p for p in generated_paths if p.relative_to(ROOT).as_posix() not in expected and p.read_text(encoding='utf-8').startswith(MARKER)]
        for target in stale:
            if check:
                bad.append(str(target.relative_to(ROOT)))
            else:
                target.unlink()
        for path, content in self.outputs.items():
            target = ROOT / path
            if not target.exists() or target.read_text(encoding='utf-8') != content:
                if check:
                    bad.append(path)
                else:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(content.encode('utf-8'))
        if bad:
            raise ValueError('Generated files differ: ' + ', '.join(bad))
        print('%d operations; %d generated types; %d constants; generated files %s.' % (len(self.operations), len(self.schemas), sum('public static final' in line for line in self.outputs[JAVA + 'EnumValues.java'].splitlines()), 'verified' if check else 'written'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        generator = Generator()
        generator.generate()
        generator.write(args.check)
    except (ValueError, KeyError, StopIteration) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
